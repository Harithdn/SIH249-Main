/* ================= DIGITAL THREAD ================= */
export function Thread() {
  const sys = useSystem();
  const [t, setT] = useState<any>(null);
  const [err, setErr] = useState<string | null>(null);

  useEffect(() => {
    let alive = true;
    get(`/api/digital-thread?aid=${sys.currentAircraft}`).then((r) => { if (alive) { setT(r); sys.markUpdated(); } })
      .catch((e) => { if (alive) setErr(String(e?.message || e)); });
    return () => { alive = false; };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [sys.refreshKey, sys.currentAircraft]);

  if (err) return <ErrorState title="DIGITAL THREAD UNAVAILABLE" message="Unable to retrieve the digital thread." detail={err} onRetry={() => sys.bumpRefresh()} />;
  if (!t) return <LoadingState label="TRACING DIGITAL THREAD" />;

  const cur = t.current;

  return (
    <div>
      <PageHeader
        title="DIGITAL THREAD"
        sub={`Sensor-to-availability pipeline for ${sys.currentAircraft}. Each stage is a live system component — the thread shows where the current prediction sits.`}
        provenance="PIPELINE VIEW · LIVE STATE"
      />

      <Panel title="PIPELINE STAGES" sub="SENSOR DATA → AIRCRAFT AVAILABILITY" icon="activity" bodyClass="p-0">
        <div className="grid grid-cols-2 divide-x divide-y divide-line border-t border-line sm:grid-cols-3 lg:grid-cols-7">
          {t.steps?.map((s: string, i: number) => {
            const active = cur && (
              (i <= 4) || (cur.failure_prob > 0.5 && i <= 8) || false
            );
            return (
              <div key={s} className={`px-3 py-2.5 ${active ? 'bg-[#14222B]' : ''}`}>
                <div className="flex items-center gap-1.5">
                  <span className={`font-mono text-[9px] ${active ? 'text-acc' : 'text-txt-faint'}`}>{String(i + 1).padStart(2, '0')}</span>
                  <span className={`font-mono text-[10px] uppercase tracking-[0.05em] ${active ? 'text-acc' : 'text-txt-dim'}`}>{s}</span>
                </div>
                {i < (t.steps?.length || 0) - 1 && <div className="mt-0.5 font-mono text-[8px] text-txt-faint">↓</div>}
              </div>
            );
          })}
        </div>
      </Panel>

      {cur ? (
        <Panel title={`LIVE EXAMPLE — ${sys.currentAircraft}`} sub={`${cur.component} · CURRENT PREDICTION`} icon="target" className="mt-3">
          <div className="grid gap-3 md:grid-cols-4">
            <Metric label="COMPONENT" value={cur.component.toUpperCase()} />
            <Metric label="FAILURE PROBABILITY" value={pctOf(cur.failure_prob * 100, 1)} st={cur.failure_prob > 0.5 ? 'crit' : 'ok'} />
            <Metric label="RUL" value={`${num(cur.rul, 1)} D`} />
            <Metric label="RECOMMENDATION" value={<span className="text-[11px] leading-snug">{cur.recommendation}</span>} />
          </div>
          <div className="mt-3 flex gap-2 border-t border-line pt-3">
            <Link className="btn" to={`/app/aircraft/${sys.currentAircraft}/diagnostics`}>OPEN DIAGNOSTICS →</Link>
            <Link className="btn btn-primary" to={`/app/work-orders?pre=${sys.currentAircraft}:${encodeURIComponent(cur.component)}`}>CREATE WORK ORDER</Link>
          </div>
        </Panel>
      ) : (
        <Panel title={`LIVE EXAMPLE — ${sys.currentAircraft}`} className="mt-3">
          <EmptyState title="NO ACTIVE PREDICTION" message="This aircraft has no elevated component risk in the current model run — the thread is in monitoring state." />
        </Panel>
      )}
    </div>
  );
}
