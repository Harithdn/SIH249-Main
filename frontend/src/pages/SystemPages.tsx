/* ================= ALERTS ================= */
export function Alerts() {
  const sys = useSystem();
  const nav = useNavigate();
  const [rows, setRows] = useState<any[] | null>(null);
  const [err, setErr] = useState<string | null>(null);
  const [sev, setSev] = useState('ALL');

  useEffect(() => {
    let alive = true;
    get('/api/alerts').then((r) => { if (alive) { setRows(r); sys.markUpdated(); } })
      .catch((e) => { if (alive) setErr(String(e?.message || e)); });
    return () => { alive = false; };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [sys.refreshKey]);

  if (err) return <ErrorState title="ALERT SERVICE UNAVAILABLE" message="Unable to retrieve active alerts." detail={err} onRetry={() => sys.bumpRefresh()} />;
  if (!rows) return <LoadingState label="FETCHING ACTIVE ALERTS" />;

  const counts: Record<string, number> = {
    ALL: rows.length,
    Critical: rows.filter((r) => r.severity === 'Critical').length,
    Warning: rows.filter((r) => r.severity === 'Warning').length,
  };
  rows.forEach((r) => { if (counts[r.severity] == null) counts[r.severity] = 1; });
  const filtered = sev === 'ALL' ? rows : rows.filter((r) => r.severity === sev);

  return (
    <div>
      <PageHeader
        title="ALERT CENTER"
        sub="Active operational alerts generated by the prediction pipeline and threshold rules, ordered by severity."
        provenance="LIVE DETECTION · SYNTHETIC DATA"
      >
        <Segmented value={sev} onChange={setSev} ariaLabel="Severity filter"
          options={Object.entries(counts).map(([k, v]) => ({ id: k, label: k.toUpperCase(), count: v }))} />
      </PageHeader>

      <Panel title="ACTIVE ALERTS" sub={`${filtered.length} ALERTS`} icon="alert" bodyClass="p-0">
        {filtered.length === 0 ? (
          <div className="p-3"><EmptyState title="NO ACTIVE ALERTS" message="No aircraft currently require immediate attention." hint={`LAST CHECK ${istTime(new Date().toISOString())}`} /></div>
        ) : (
          <div className="overflow-x-auto">
            <table className="dt">
              <thead><tr><th>TIME</th><th>SEVERITY</th><th>TYPE</th><th>AIRCRAFT</th><th>COMPONENT</th><th>MESSAGE</th><th>REQUIRED ACTION</th><th>STATUS</th><th></th></tr></thead>
              <tbody>
                {filtered.map((a, i) => (
                  <tr key={i}>
                    <td className="mono">{istTime(a.timestamp)}</td>
                    <td><StatusTag s={a.severity === 'Critical' ? 'Critical' : a.severity === 'Warning' ? 'High' : 'Low'} label={a.severity === 'Critical' ? 'CRITICAL' : a.severity === 'Warning' ? 'WARNING' : a.severity.toUpperCase()} /></td>
                    <td>{a.type}</td>
                    <td className="mono">{a.aircraft_id || '—'}</td>
                    <td>{a.component || '—'}</td>
                    <td style={{ whiteSpace: 'normal' }} className="max-w-[320px]">{a.message}</td>
                    <td style={{ whiteSpace: 'normal' }} className="max-w-[240px] text-[11.5px]">{a.action}</td>
                    <td><StatusTag s={a.status} /></td>
                    <td>
                      {a.aircraft_id && (
                        <button className="btn btn-xs" onClick={() => nav(`/app/aircraft/${a.aircraft_id}/diagnostics`)}>DIAGNOSTICS →</button>
                      )}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </Panel>
    </div>
  );
}

/* ================= MODEL PERFORMANCE ================= */
export function Models() {
  const sys = useSystem();
  const [rows, setRows] = useState<any[] | null>(null);
  const [err, setErr] = useState<string | null>(null);
  const [target, setTarget] = useState('failure');
  const [notice, setNotice] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  const load = () => get('/api/models');
  useEffect(() => {
    let alive = true;
    load().then((r) => { if (alive) { setRows(r); sys.markUpdated(); } })
      .catch((e) => { if (alive) setErr(String(e?.message || e)); });
    return () => { alive = false; };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [sys.refreshKey]);

  if (err) return <ErrorState title="MODEL REGISTRY UNAVAILABLE" message="Unable to retrieve the model registry." detail={err} onRetry={() => sys.bumpRefresh()} />;
  if (!rows) return <LoadingState label="FETCHING MODEL REGISTRY" />;

  const train = async () => {
    setBusy(true);
    try {
      const r = await post('/api/models/train', { target, kind: target === 'rul' ? 'regression' : target });
      setNotice(`MODEL ${r.version} TRAINED ON SYNTHETIC DATA — DEMO EVALUATION METICS ONLY`);
      setRows(await load());
    } catch (e: any) { setNotice(`TRAINING FAILED — ${String(e?.message || e).slice(0, 120)}`); }
    setBusy(false);
  };

  const fmtMetric = (k: string, v: any) => {
    if (typeof v !== 'number') return String(v);
    if (['f1', 'precision', 'recall', 'contamination'].includes(k)) return num(v, 3);
    return num(v, 1);
  };

  return (
    <div>
      <PageHeader
        title="MODEL PERFORMANCE"
        sub="Registered model versions with their recorded evaluation metrics. Metrics are demo evaluations on synthetic data — not real-world performance."
        provenance="REGISTRY · DEMO EVALUATION ON SYNTHETIC DATA"
      />

      {notice && <div className="mb-3 border border-line-strong bg-surface2 px-3 py-2 font-mono text-[10.5px] uppercase tracking-[0.06em] text-acc">{notice}</div>}

      <div className="grid gap-3">
        {rows.map((m, i) => (
          <Panel key={i} title={`${m.name.toUpperCase()} — ${m.version}`} sub={m.purpose} icon="chip"
            right={<StateTag st={m.status === 'Active' ? 'ok' : 'off'} label={m.status.toUpperCase()} />}>
            <div className="grid gap-x-8 gap-y-2 sm:grid-cols-2 lg:grid-cols-4">
              <div>
                <div className="tlabel mb-1">EVALUATION METRICS</div>
                {Object.entries(m.metrics || {}).filter(([k]) => k !== 'note').map(([k, v]) => (
                  <KV key={k} k={k.replace(/_/g, ' ')} v={fmtMetric(k, v)} />
                ))}
                {Object.keys(m.metrics || {}).filter((k) => k !== 'note').length === 0 && <NotAvailable />}
              </div>
              <div>
                <div className="tlabel mb-1">REGISTRATION</div>
                <KV k="VERSION" v={m.version} />
                <KV k="STATUS" v={m.status.toUpperCase()} />
                <KV k="LAST TRAINED" v={istDateTime(m.trained)} />
              </div>
              <div className="lg:col-span-2">
                <div className="tlabel mb-1">NOT AVAILABLE IN REGISTRY</div>
                <div className="font-mono text-[10px] leading-relaxed text-txt-faint">
                  CONFUSION MATRIX · TRAINING DATA VOLUME · PREDICTION COUNT — NOT RECORDED BY THE PROTOTYPE REGISTRY.
                  FEATURE CONTRIBUTIONS ARE COMPUTED PER PREDICTION (SEE DIAGNOSTICS), NOT STORED AS GLOBAL IMPORTANCE.
                </div>
                {m.metrics?.note && <div className="mt-2 border border-[#2a2312] bg-warn-dim px-2 py-1 font-mono text-[9px] uppercase tracking-[0.06em] text-warn">{m.metrics.note}</div>}
              </div>
            </div>
          </Panel>
        ))}

        <Panel title="TRAINING — DEMO" sub="RETRAINS THE PIPELINE ON SYNTHETIC DATA" icon="gear">
          <div className="flex flex-wrap items-center gap-2">
            <select className="inp max-w-xs" value={target} onChange={(e) => setTarget(e.target.value)} aria-label="Training target">
              <option value="failure">CLASSIFICATION — FAILURE</option>
              <option value="rul">REGRESSION — RUL</option>
              <option value="anomaly">ANOMALY DETECTION</option>
            </select>
            <button className="btn btn-primary" onClick={train} disabled={busy}><Icon name="refresh" size={12} /> {busy ? 'TRAINING…' : 'TRAIN MODEL'}</button>
            <span className="font-mono text-[9.5px] leading-relaxed tracking-[0.05em] text-txt-faint">
              TRAINS ON THE SEEDED SYNTHETIC DATASET · RECORDED METRICS ARE DEMO EVALUATIONS ONLY.
            </span>
          </div>
        </Panel>
      </div>
    </div>
  );
}

